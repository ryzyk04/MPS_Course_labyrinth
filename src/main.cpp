// Лабиринт, уровень 1, на матрице 8x8 (MAX7219) с 4 кнопками
//
// Матрица:      VCC -> 5V, GND -> GND, DIN -> 11, CS -> 10, CLK -> 13
// Кнопки:       вверх -> 2, вниз -> 3, влево -> 4, вправо -> 5
//               (вторым контактом каждой кнопки на GND)
// Светодиод:    пин 12 -> резистор -> светодиод (+), (-) -> GND

// ---------- Матрица ----------
const uint8_t PIN_DIN = 11;
const uint8_t PIN_CS  = 10;
const uint8_t PIN_CLK = 13;
const uint8_t BRIGHTNESS = 4;   // 0..15

// ---------- Светодиод-индикатор удара о стену ----------
const uint8_t PIN_ALERT_LED = 12;
const uint16_t ALERT_MS = 100;  // сколько горит после удара

// ---------- Светодиоды сложности ----------
const uint8_t PIN_LED_EASY   = 6;
const uint8_t PIN_LED_MEDIUM = 7;
const uint8_t PIN_LED_HARD   = 8;

// ---------- Кнопки (между пином и GND) ----------
const uint8_t PIN_UP    = 2;
const uint8_t PIN_DOWN  = 3;
const uint8_t PIN_LEFT  = 4;
const uint8_t PIN_RIGHT = 5;

const uint8_t BTN_PINS[4] = {PIN_UP, PIN_DOWN, PIN_LEFT, PIN_RIGHT};
const int8_t KEY_UP = 0, KEY_DOWN = 1, KEY_LEFT = 2, KEY_RIGHT = 3;

// ---------- Лабиринты: 9 лёгких (4x4), 9 средних (6x6), 9 сложных (8x8) ----------
// Координаты: (0, 0) - левый нижний угол, x растёт вправо, y растёт вверх.
// Стена стоит МЕЖДУ двумя соседними клетками и не даёт перейти между ними
// в обе стороны. Стены не отображаются, но игрока не пропускают.
// Все данные лежат во флеш-памяти (PROGMEM), в оперативную копируется только текущий уровень.
struct Wall { uint8_t x1, y1, x2, y2; };   // клетки по обе стороны стены

enum Difficulty : uint8_t { EASY, MEDIUM, HARD };

struct Level {
  uint8_t size;                // сторона лабиринта в клетках
  uint8_t difficulty;          // EASY / MEDIUM / HARD
  uint8_t startX, startY;
  uint8_t finishX, finishY;
  const Wall *walls;           // адрес массива стен во флеш-памяти
  uint8_t wallCount;
};

