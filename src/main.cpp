const bool SHOW_FINISH = true;   // false - финиш скрыт: не рисуется и победа отключена

const uint16_t REPEAT_DELAY_MS = 250;  // через сколько удержание начинает повторяться
const uint16_t REPEAT_RATE_MS  = 150;  // и как часто потом

// ---------- Драйвер MAX7219 ----------
const uint8_t REG_DECODE    = 0x09;
const uint8_t REG_INTENSITY = 0x0A;
const uint8_t REG_SCANLIMIT = 0x0B;
const uint8_t REG_SHUTDOWN  = 0x0C;
const uint8_t REG_TEST      = 0x0F;

void send(uint8_t reg, uint8_t value) {
  digitalWrite(PIN_CS, LOW);
  shiftOut(PIN_DIN, PIN_CLK, MSBFIRST, reg);
  shiftOut(PIN_DIN, PIN_CLK, MSBFIRST, value);
  digitalWrite(PIN_CS, HIGH);
}

void showFrame(const uint8_t rows[8]) {
  for (uint8_t r = 0; r < 8; r++) send(r + 1, rows[r]);
}

// ---------- Кнопки ----------
// Возвращает номер нажатой кнопки (KEY_*) или -1
int8_t scanKey() {
  for (uint8_t i = 0; i < 4; i++) {
    if (digitalRead(BTN_PINS[i]) == LOW) return i;
  }
  return -1;
}

// ---------- Игра ----------
Level level;   // текущий лабиринт (копия из флеш-памяти)
int8_t levelIndex = -1;
uint8_t px = 0, py = 0;
int8_t lastKey = -1;
uint32_t keyTime = 0;      // когда клавиша была нажата
uint32_t lastRepeat = 0;
uint32_t alertUntil = 0;   // до какого момента горит светодиод-индикатор

// Есть ли стена между соседними клетками (в любую сторону)
bool wallBetween(uint8_t x1, uint8_t y1, uint8_t x2, uint8_t y2) {
  for (uint8_t i = 0; i < level.wallCount; i++) {
    Wall w;
    memcpy_P(&w, &level.walls[i], sizeof(Wall));
    if (w.x1 == x1 && w.y1 == y1 && w.x2 == x2 && w.y2 == y2) return true;
    if (w.x1 == x2 && w.y1 == y2 && w.x2 == x1 && w.y2 == y1) return true;
  }
  return false;
}

void tryMove(int8_t dx, int8_t dy) {
  if (!gameActive) return;
  int8_t nx = px + dx;
  int8_t ny = py + dy;
  bool outside = nx < 0 || nx >= level.size || ny < 0 || ny >= level.size;

  if (outside || wallBetween(px, py, nx, ny)) {
    bus.smallError();
    alertUntil = millis() + ALERT_MS;   // врезались - зажигаем светодиод
  } else {
    px = nx;
    py = ny;
  }
}

void handleKey(int8_t key) {
  if (key == KEY_UP)    tryMove(0, 1);
  if (key == KEY_DOWN)  tryMove(0, -1);
  if (key == KEY_LEFT)  tryMove(-1, 0);
  if (key == KEY_RIGHT) tryMove(1, 0);

  Serial.print("x=");
  Serial.print(px);
  Serial.print(" y=");
  Serial.println(py);
}

// Один из девяти лабиринтов выбранной сложности, воспроизводимо по сиду.
void pickLevel() {
  levelIndex = bus.status.difficulty * 9 + bus.status.seed % 9;
  memcpy_P(&level, &LEVELS[levelIndex], sizeof(Level));
  px = level.startX;
  py = level.startY;
  gameActive = true;
  lastKey = -1; keyTime = lastRepeat = millis(); alertUntil = 0;

  // светодиоды сложности: 6 - лёгкий, 7 - средний, 8 - сложный
  digitalWrite(PIN_LED_EASY,   level.difficulty == EASY);
  digitalWrite(PIN_LED_MEDIUM, level.difficulty == MEDIUM);
  digitalWrite(PIN_LED_HARD,   level.difficulty == HARD);

  Serial.print("Уровень сложности: ");
  Serial.print(level.difficulty == EASY ? "лёгкий" : level.difficulty == MEDIUM ? "средний" : "сложный");
  // Serial.print(" (лабиринт ");
  // Serial.print(levelIndex + 1);
  // Serial.print(" из ");
  // Serial.print(LEVEL_COUNT);
  // Serial.println(")");
}

void win() {
  gameActive = false;
  solvedAt = millis();
  bus.solved();
  Serial.println(F("SOLVED: жду следующую команду игры"));
}

void draw(uint32_t now) {
  uint8_t frame[8] = {0, 0, 0, 0, 0, 0, 0, 0};
  if (!gameActive) {
    bool solved = bus.status.state == ModuleBus::SOLVED;
    if (solved && (now - solvedAt >= 1600 || ((now - solvedAt) / 200) % 2 == 0))
      memset(frame, 255, sizeof(frame));
    showFrame(frame);
    return;
  }

  // стены не рисуем - о них сообщает только светодиод
  // финиш мигает
  if (SHOW_FINISH && (now / 300) % 2) frame[7 - level.finishY] |= 0x80 >> level.finishX;
  // игрок светится постоянно
  frame[7 - py] |= 0x80 >> px;   // строка 0 матрицы - верхняя, поэтому 7 - y

  showFrame(frame);
}

void setup() {
  Serial.begin(9600);
  pinMode(PIN_DIN, OUTPUT);
  pinMode(PIN_CS, OUTPUT);
  pinMode(PIN_CLK, OUTPUT);
  pinMode(PIN_ALERT_LED, OUTPUT);
  pinMode(PIN_LED_EASY, OUTPUT);
  pinMode(PIN_LED_MEDIUM, OUTPUT);
  pinMode(PIN_LED_HARD, OUTPUT);
  digitalWrite(PIN_CS, HIGH);

  for (uint8_t i = 0; i < 4; i++) pinMode(BTN_PINS[i], INPUT_PULLUP);

  send(REG_TEST, 0);
  send(REG_DECODE, 0);
  send(REG_SCANLIMIT, 7);
  send(REG_INTENSITY, BRIGHTNESS);
  send(REG_SHUTDOWN, 1);

  bus.begin(ModuleBus::LABYRINTH, ModuleBus::LABYRINTH_ADDRESS);
  draw(millis());
  Serial.println(F("WAITING_FOR_COMMAND: I2C 0x12, SDA=A4 SCL=A5"));
}

void loop() {
  uint32_t now = millis();
  PuzzleI2c::Action action = bus.update();
  if (action == PuzzleI2c::NEW_GAME) pickLevel();
  else if (action == PuzzleI2c::HALT) {
    gameActive = false;
    digitalWrite(PIN_LED_EASY, LOW); digitalWrite(PIN_LED_MEDIUM, LOW); digitalWrite(PIN_LED_HARD, LOW);
    digitalWrite(PIN_ALERT_LED, LOW);
  }
  if (!gameActive) { draw(now); return; }
  int8_t key = scanKey();

  if (key != lastKey) {
    lastKey = key;
    keyTime = now;
    lastRepeat = now;
    if (key >= 0) handleKey(key);
  } else if (key >= 0 && now - keyTime > REPEAT_DELAY_MS &&
             now - lastRepeat > REPEAT_RATE_MS) {
    lastRepeat = now;
    handleKey(key);   // повтор при удержании
  }

  digitalWrite(PIN_ALERT_LED, (int32_t)(alertUntil - now) > 0);

  if (SHOW_FINISH && px == level.finishX && py == level.finishY) win();

  draw(now);
  delay(2);
}
